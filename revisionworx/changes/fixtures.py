"""Deterministic sample engineering changes for tests, GUI development and QA.

:func:`sample_memory_service` needs no workspace (GUI view-model tests). :func:`create_sample_workspace`
builds a real, disposable workspace with a project, documents, revisions and changes in every main state,
using only public core calls. Change ids, numbers, times and actors are fixed; core document and revision
ids are generated by the core and therefore differ between runs.
"""
from __future__ import annotations

import hashlib
from pathlib import Path

from .catalog import MemoryCatalog
from .service import ChangeService
from .store import MemoryStore

ALICE = {"user": "alice", "host": "ws-01"}
BOB = {"user": "bob", "host": "ws-02"}
CAROL = {"user": "carol", "host": "ws-03"}


class FixedClock:
    """2026-01-05T09:00:00+00:00, advancing one minute per call."""

    def __init__(self, start_minute: int = 0):
        self.n = start_minute

    def __call__(self) -> str:
        m = self.n
        self.n += 1
        return f"2026-01-{5 + m // 1440:02d}T{(9 + (m // 60)) % 24:02d}:{m % 60:02d}:00+00:00"


class SequentialIds:
    def __init__(self, seed: str = "fixture"):
        self.seed, self.n = seed, 0

    def __call__(self, prefix: str) -> str:
        self.n += 1
        return f"{prefix}_{hashlib.sha256(f'{self.seed}:{prefix}:{self.n}'.encode()).hexdigest()[:32]}"


class Actors:
    """Switchable current actor: ``with actors.as_(BOB): ...``."""

    def __init__(self, default: dict = ALICE):
        self.current = dict(default)

    def __call__(self) -> dict:
        return dict(self.current)

    def as_(self, actor: dict):
        outer = self

        class _Ctx:
            def __enter__(self):
                self.prev, outer.current = outer.current, dict(actor)

            def __exit__(self, *exc):
                outer.current = self.prev
        return _Ctx()


def deterministic(store, catalog=None, seed: str = "fixture") -> tuple[ChangeService, Actors]:
    actors = Actors()
    return ChangeService(store, catalog, clock=FixedClock(), ids=SequentialIds(seed), actor=actors), actors


def populate(svc: ChangeService, actors: Actors, doc_ids: list[str]) -> dict:
    """Changes in every main state over the given documents. Returns name -> change id."""
    d0, d1 = doc_ids[0], doc_ids[1]
    out = {}
    draft = svc.create_request("Add chamfer to bracket edges", "Sharp edges injured an assembler",
                               category="design", priority="high",
                               affected=[{"item_type": "document", "item_id": d0, "action": "revise"},
                                         {"item_type": "part", "label": "P-1001", "baseline_label": "B"}])
    out["draft"] = draft.id
    rev = svc.create_request("Update frame drawing notes", "Notes reference a withdrawn standard",
                             category="documentation", affected=[{"item_type": "document", "item_id": d1}])
    rev = svc.submit(rev.id)
    out["submitted"] = rev.id
    rejected = svc.create_request("Change bracket finish to chrome", "Customer preference",
                                  affected=[{"item_type": "document", "item_id": d0}])
    svc.submit(rejected.id)
    with actors.as_(BOB):
        svc.begin_review(rejected.id)
        out["rejected"] = svc.reject(rejected.id, "Chrome plating is not RoHS-compliant here").id
    approved = svc.create_request("Increase bracket thickness 3 mm -> 4 mm", "Fatigue cracks in test rig",
                                  priority="urgent", affected=[{"item_type": "document", "item_id": d0},
                                                               {"item_type": "assembly", "label": "A-200",
                                                                "action": "review"}])
    svc.submit(approved.id)
    with actors.as_(BOB):
        svc.begin_review(approved.id)
        approved = svc.approve(approved.id, "Agreed; check the frame drawing too", role="Design lead")
    out["approved"] = approved.id
    eco = svc.create_order([approved.id], actions=["Update bracket model and drawing",
                                                   {"title": "Notify supplier", "assignee": "carol"}])
    out["order"] = eco.id
    return out


def sample_memory_service() -> tuple[ChangeService, Actors, MemoryCatalog, dict]:
    """In-memory service with two fake documents and :func:`populate` applied."""
    cat = MemoryCatalog()
    for i, label in enumerate(("DWG-100 Bracket", "DWG-200 Frame")):
        doc = f"doc_{hashlib.sha256(label.encode()).hexdigest()[:32]}"
        cat.add_document(doc, label)
        cat.add_revision(doc, f"rev_{hashlib.sha256((label + 'A').encode()).hexdigest()[:32]}", "A")
    svc, actors = deterministic(MemoryStore(), cat)
    ids = populate(svc, actors, list(cat.documents))
    return svc, actors, cat, ids


def create_sample_workspace(location: Path) -> dict:
    """A disposable workspace at ``location`` with sample changes. Returns ids for tests and demos."""
    from .. import documents, projects
    from ..projects import NewProject
    from ..workspace import Workspace
    from . import WorkspaceCatalog, WorkspaceStore
    location = Path(location)
    (location / "Engineering").mkdir(parents=True, exist_ok=True)
    with Workspace.create(location, "Change control sample") as ws:
        projects.add_root(ws, "Engineering", location / "Engineering")
        proj = projects.create_project(ws, NewProject(name="Hydraulic power unit", number="J-1001",
                                                      customer="Acme"))
        folder = projects.project_folder(ws, proj)
        files = {"DWG-100": folder / "03 Drawings" / "Native" / "bracket.idw",
                 "DWG-200": folder / "03 Drawings" / "Native" / "frame.idw"}
        doc_ids = []
        for number, path in files.items():
            path.write_bytes(f"{number} revision A".encode())
            doc, _ = documents.register_document(ws, proj["id"], path, number=number)
            doc_ids.append(doc["id"])
        svc, actors = deterministic(WorkspaceStore(ws), WorkspaceCatalog(ws))
        ids = populate(svc, actors, doc_ids)
        return {"workspace_id": ws.id, "project_id": proj["id"], "documents": doc_ids, "changes": ids}
